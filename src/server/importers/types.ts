export const SOURCES = ['meta', 'indeed', 'driverhub'] as const;
export type Source = (typeof SOURCES)[number];
export type Issue = { row?: number; column?: string; message: string };
export type Raw = Record<string, string>;
export type Period = { start: string; end: string };
export type BaseRow = { rowNo: number; raw: Raw };
export type MetaRow = BaseRow & {
  adSetName: string;
  delivery: string;
  results: number | null;
  resultIndicator: string;
  spend: string;
  impressions: number;
  reach: number | null;
  frequency: string | null;
  uniqueLinkClicks: number | null;
  budget: string | null;
  budgetType: string;
  starts: string | null;
  ends: string | null;
};
export type IndeedRow = BaseRow & {
  campaign: string;
  premium: string;
  impressions: number;
  clicks: number;
  applyStarts: number;
  applies: number;
  spend: string;
  jobCount: number;
  rowKind: 'job' | 'bundle' | 'organic' | 'plan';
};
export type CandidateRow = BaseRow & {
  firstName: string | null;
  lastName: string | null;
  appCreated: string | null;
  recruitingStatus: string | null;
  referralSource: string | null;
  rejectionReason: string | null;
  appStatus: string | null;
  ownerOperator: string | null;
  yearsExp: string | null;
  signedDate: string | null;
  cdlExp: string | null;
  endorsements: string | null;
  equipment: string | null;
  startDate: string | null;
  position: string | null;
  location: string | null;
  daysInFunnel: number | null;
  ambiguousFields: string[];
  values: Record<string, string[]>;
};
export type ImportRow = MetaRow | IndeedRow | CandidateRow;
export type Totals = Record<string, string | number | null>;
export type ParseResult<R extends ImportRow = ImportRow> = {
  rows: R[];
  totals: Totals;
  warnings: Issue[];
  errors: Issue[];
  detectedPeriod?: Period;
  detectedSnapshot?: string;
};
export const MAX_BYTES = 10 * 1024 * 1024;
export const MAX_ROWS = 50_000;
